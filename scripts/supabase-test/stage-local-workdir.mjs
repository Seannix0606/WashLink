#!/usr/bin/env node
// Builds the gitignored, unlinked local Supabase test workdir `.local-supabase-test/`.
//
// Why (W1 PLAN section 0/2/8, decisions D-1 and D-11):
// - The committed migrations use `YYYY_MM_DD_<desc>.sql`, which Supabase CLI parses as version
//   `2026`, so they collide in schema_migrations. The staged copy gets 14-digit versions while the
//   file contents stay byte-identical.
// - The local test baseline must never live in the repo's supabase/ folder at all: `db push`
//   sends supabase/migrations/, and `test db` (also with --linked / --db-url) runs EVERY .sql
//   under supabase/tests/. Sources live in scripts/supabase-test/baseline/, injected here only:
//     00000000000000  local_test_baseline.sql                (profiles, workers, bookings)
//     20260417000002  local_test_baseline_owner_policies.sql (needs bookings.shop_id from
//                     2026_04_17 = 20260417000001; a migration, not the seed, so later W2
//                     migrations can drop or replace these policies)
//   test_helpers.sql, test_helpers_certifications.sql (W7), test_helpers_contract_templates.sql (W8),
//   test_helpers_worker_contracts.sql (W9), test_helpers_owner_relationships.sql (W10), test_helpers_oversight.sql (W11),
//   test_helpers_moderation.sql (W14) then test_helpers_scheduling.sql (W12) are the staged seed (helpers only), in order.
// - The staged dir never contains `.temp/project-ref`, so the CLI cannot target a linked project.
// - W2 (S10/S11): the repo config keeps [db.seed] enabled = false (only the staged copy enables
//   it), the staged project_id must end in "-local-test", and no .sql may exist under supabase/
//   except supabase/migrations/*.sql and supabase/tests/database/*.sql.
//
// Node 24, no dependencies. Never writes inside the repo's supabase/ folder.

import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const STAGED_DIRECTORY_NAME = '.local-supabase-test'
export const BASELINE_MIGRATION_NAME = '00000000000000_local_test_baseline_only.sql'
export const OWNER_POLICIES_MIGRATION_NAME = '20260417000002_local_test_baseline_owner_policies.sql'
// The owner policies need bookings.shop_id, added by this committed migration.
export const OWNER_POLICIES_PREDECESSOR = '2026_04_17_add_shops_and_booking_location.sql'
export const BASELINE_SOURCE_DIRECTORY = path.join('scripts', 'supabase-test', 'baseline')
const BASELINE_SOURCE_NAME = 'local_test_baseline.sql'
const OWNER_POLICIES_SOURCE_NAME = 'local_test_baseline_owner_policies.sql'
// Seeded in this order (second file: W7 certification helpers, third: W8 contract template helpers, fourth: W9
// worker contract helpers, fifth: W10 owner relationship helpers, sixth: W11 oversight helpers, seventh: W14 moderation
// helpers, eighth: W12 scheduling helpers; test_helpers.sql is at its size limit).
export const HELPERS_SOURCE_NAMES = ['test_helpers.sql', 'test_helpers_certifications.sql', 'test_helpers_contract_templates.sql',
  'test_helpers_worker_contracts.sql', 'test_helpers_owner_relationships.sql', 'test_helpers_oversight.sql', 'test_helpers_moderation.sql',
  'test_helpers_scheduling.sql']
const PROJECT_ID_LINE = 'project_id = "washlink"'
const STAGED_PROJECT_ID_LINE = 'project_id = "washlink-local-test"'
const SEED_PATHS_LINE = 'sql_paths = ["./seed.sql"]'
// W2 S10: the repo keeps the seed disabled; only the staged copy enables it.
const SEED_SECTION_LINE = '[db.seed]'
const SEED_DISABLED_LINE = 'enabled = false'
const SEED_ENABLED_LINE = 'enabled = true'
export const LOCAL_TEST_PROJECT_ID_SUFFIX = '-local-test'
const PROJECT_ID_PATTERN = /^project_id\s*=\s*"([^"]*)"$/
// The helpers seed is staged OUTSIDE supabase/tests/: `supabase test db` runs every .sql file
// under tests/ as a pgTAP file, which would execute the helpers as tests.
export const STAGED_BASELINE_DIRECTORY = 'local_test_baseline'
const STAGED_SEED_PATHS_LINE = `sql_paths = [${HELPERS_SOURCE_NAMES.map((name) => `"./${STAGED_BASELINE_DIRECTORY}/${name}"`).join(', ')}]`
const LEGACY_NAME_PATTERN = /^(\d{4})_(\d{2})_(\d{2})_([a-z0-9_]+)\.sql$/
const TIMESTAMP_NAME_PATTERN = /^\d{14}_[a-z0-9_]+\.sql$/
const MARKER_TEXT = [
  'STAGED LOCAL TEST WORKDIR - generated by scripts/supabase-test/stage-local-workdir.mjs.',
  'Contains the LOCAL TEST BASELINE. Use only with --local against the Docker stack.',
  'Never link this directory, never run db push from it. Regenerated on every run.',
  '',
].join('\n')

function stagedVersion(stagedName) {
  return stagedName.slice(0, 14)
}

function baselineSourceName(fileName) {
  return `scripts/supabase-test/baseline/${fileName}`
}

// Puts the baseline first and the owner-policies baseline directly after the staged 2026_04_17
// copy. Throws if the predecessor is missing or if any committed migration would collide with,
// or sort between, the predecessor and the injected version.
export function planBaselineMigrations(plannedMigrations) {
  const predecessorIndex = plannedMigrations.findIndex(
    ({ sourceName }) => sourceName === OWNER_POLICIES_PREDECESSOR,
  )
  if (predecessorIndex === -1) {
    throw new Error(`Owner policies baseline needs ${OWNER_POLICIES_PREDECESSOR}; not found`)
  }
  const predecessorVersion = stagedVersion(plannedMigrations[predecessorIndex].stagedName)
  const ownerVersion = stagedVersion(OWNER_POLICIES_MIGRATION_NAME)
  const intruder = plannedMigrations.find(({ stagedName }) => {
    const version = stagedVersion(stagedName)
    return version > predecessorVersion && version <= ownerVersion
  })
  if (predecessorVersion >= ownerVersion || intruder) {
    const culprit = intruder ?? plannedMigrations[predecessorIndex]
    throw new Error(
      `Migration ${culprit.sourceName} (${culprit.stagedName}) breaks the slot for ${OWNER_POLICIES_MIGRATION_NAME}`,
    )
  }
  return [
    {
      sourceName: baselineSourceName(BASELINE_SOURCE_NAME),
      stagedName: BASELINE_MIGRATION_NAME,
      baselineFile: BASELINE_SOURCE_NAME,
    },
    ...plannedMigrations.slice(0, predecessorIndex + 1),
    {
      sourceName: baselineSourceName(OWNER_POLICIES_SOURCE_NAME),
      stagedName: OWNER_POLICIES_MIGRATION_NAME,
      baselineFile: OWNER_POLICIES_SOURCE_NAME,
    },
    ...plannedMigrations.slice(predecessorIndex + 1),
  ]
}

// `supabase test db` runs every .sql file under supabase/tests/ (also with --linked/--db-url),
// so the repo may hold .sql files only under supabase/tests/database/.
export function findSqlOutsideTestDatabase(sourceTests) {
  return listSqlFiles(sourceTests)
    .filter((parts) => parts.length < 2 || parts[0] !== 'database')
    .map((parts) => parts.join('/'))
    .sort()
}

// W2 S11: the whole supabase/ folder may hold .sql only as supabase/migrations/*.sql and
// supabase/tests/database/*.sql (no seed.sql, no nested folders). Anything else could be
// picked up by db reset (seed), db push or test db when the CLI runs from the repo root.
export function findStraySqlUnderSupabase(sourceSupabase) {
  return listSqlFiles(sourceSupabase)
    .filter((parts) => {
      const isMigration = parts.length === 2 && parts[0] === 'migrations'
      const isPgTap = parts.length === 3 && parts[0] === 'tests' && parts[1] === 'database'
      return !isMigration && !isPgTap
    })
    .map((parts) => parts.join('/'))
    .sort()
}

function listSqlFiles(rootDirectory) {
  const found = []
  if (!fs.existsSync(rootDirectory)) {
    return found
  }
  const walk = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const fullPath = path.join(directory, entry.name)
      if (entry.isDirectory()) {
        walk(fullPath)
      } else if (entry.name.toLowerCase().endsWith('.sql')) {
        found.push(path.relative(rootDirectory, fullPath).split(path.sep))
      }
    }
  }
  walk(rootDirectory)
  return found
}

export function readProjectId(configText) {
  for (const line of configText.split(/\r?\n/)) {
    const match = PROJECT_ID_PATTERN.exec(line.trim())
    if (match) {
      return match[1]
    }
  }
  return null
}

// W2 S11: a staged (or about-to-be-used) config must name a *-local-test project.
export function assertLocalTestProjectId(configText, label = 'staged config.toml') {
  const projectId = readProjectId(configText)
  if (!projectId || !projectId.endsWith(LOCAL_TEST_PROJECT_ID_SUFFIX)) {
    throw new Error(
      `${label}: project_id must end with "${LOCAL_TEST_PROJECT_ID_SUFFIX}", found ${JSON.stringify(projectId)}`,
    )
  }
  return projectId
}

export function computeStagedMigrationNames(migrationFileNames) {
  const sortedNames = [...migrationFileNames].sort()
  const sequenceByDate = new Map()
  const planned = sortedNames.map((sourceName) => {
    if (TIMESTAMP_NAME_PATTERN.test(sourceName)) {
      return { sourceName, stagedName: sourceName }
    }
    const legacyMatch = LEGACY_NAME_PATTERN.exec(sourceName)
    if (!legacyMatch) {
      throw new Error(`Unknown migration file name, refusing to stage: ${sourceName}`)
    }
    const [, year, month, day, description] = legacyMatch
    const dateKey = `${year}${month}${day}`
    const sequence = (sequenceByDate.get(dateKey) ?? 0) + 1
    sequenceByDate.set(dateKey, sequence)
    const stagedName = `${dateKey}${String(sequence).padStart(6, '0')}_${description}.sql`
    return { sourceName, stagedName }
  })
  // Return in the order the CLI applies them (lexical staged name), not source-name order:
  // '_' sorts after digits, so a 14-digit source name would otherwise precede legacy names.
  planned.sort((left, right) => (left.stagedName < right.stagedName ? -1 : 1))
  const seenVersions = new Map()
  for (const { sourceName, stagedName } of planned) {
    const version = stagedVersion(stagedName)
    if (seenVersions.has(version)) {
      throw new Error(
        `Duplicate staged migration version ${version}: ${seenVersions.get(version)} and ${sourceName}`,
      )
    }
    seenVersions.set(version, sourceName)
  }
  return planned
}

function sha256OfFile(filePath) {
  return createHash('sha256').update(fs.readFileSync(filePath)).digest('hex')
}

function isInsideOrEqual(candidatePath, parentPath) {
  const relative = path.relative(parentPath, candidatePath)
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative))
}

function assertSafeOutputDirectory(repoRoot, outputDirectory) {
  const expected = path.resolve(repoRoot, STAGED_DIRECTORY_NAME)
  const resolved = path.resolve(outputDirectory)
  if (isInsideOrEqual(resolved, path.resolve(repoRoot, 'supabase', 'migrations'))) {
    throw new Error(`Refusing to stage inside supabase/migrations: ${resolved}`)
  }
  if (resolved !== expected) {
    throw new Error(`Refusing to stage outside ${expected}: ${resolved}`)
  }
  return resolved
}

function rewriteConfig(configText) {
  const lines = configText.split(/\r?\n/)
  const projectIndex = lines.findIndex((line) => line.trim() === PROJECT_ID_LINE)
  const seedIndex = lines.findIndex((line) => line.trim() === SEED_PATHS_LINE)
  if (projectIndex === -1) {
    throw new Error(`supabase/config.toml is missing the line: ${PROJECT_ID_LINE}`)
  }
  if (seedIndex === -1) {
    throw new Error(`supabase/config.toml is missing the line: ${SEED_PATHS_LINE}`)
  }
  const sectionIndex = lines.findIndex((line) => line.trim() === SEED_SECTION_LINE)
  let enabledIndex = -1
  for (let index = sectionIndex + 1; sectionIndex !== -1 && index < lines.length; index += 1) {
    const trimmed = lines[index].trim()
    if (trimmed.startsWith('[')) {
      break
    }
    if (trimmed === SEED_DISABLED_LINE) {
      enabledIndex = index
      break
    }
  }
  if (enabledIndex === -1) {
    throw new Error(
      `supabase/config.toml must keep the seed disabled: "${SEED_DISABLED_LINE}" missing under ${SEED_SECTION_LINE}`,
    )
  }
  lines[projectIndex] = STAGED_PROJECT_ID_LINE
  lines[seedIndex] = STAGED_SEED_PATHS_LINE
  lines[enabledIndex] = SEED_ENABLED_LINE
  const stagedText = lines.join('\n')
  assertLocalTestProjectId(stagedText)
  return stagedText
}

function copyFileVerified(sourcePath, targetPath) {
  fs.mkdirSync(path.dirname(targetPath), { recursive: true })
  fs.copyFileSync(sourcePath, targetPath)
  if (sha256OfFile(sourcePath) !== sha256OfFile(targetPath)) {
    throw new Error(`Staged copy is not byte-identical: ${targetPath}`)
  }
}

export function stageLocalWorkdir({ repoRoot, outputDirectory } = {}) {
  const root = path.resolve(repoRoot ?? defaultRepoRoot())
  const output = assertSafeOutputDirectory(
    root,
    outputDirectory ?? path.join(root, STAGED_DIRECTORY_NAME),
  )
  const sourceSupabase = path.join(root, 'supabase')
  const sourceMigrations = path.join(sourceSupabase, 'migrations')
  const sourceTests = path.join(sourceSupabase, 'tests')
  const sourceBaseline = path.join(root, BASELINE_SOURCE_DIRECTORY)

  // Validate everything before deleting the previous staged dir.
  const configText = rewriteConfig(fs.readFileSync(path.join(sourceSupabase, 'config.toml'), 'utf8'))
  const migrationNames = fs
    .readdirSync(sourceMigrations, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
  const plannedMigrations = planBaselineMigrations(computeStagedMigrationNames(migrationNames))
  for (const name of [BASELINE_SOURCE_NAME, OWNER_POLICIES_SOURCE_NAME, ...HELPERS_SOURCE_NAMES]) {
    if (!fs.existsSync(path.join(sourceBaseline, name))) {
      throw new Error(`Local test baseline file not found: ${path.join(sourceBaseline, name)}`)
    }
  }
  const straySql = findStraySqlUnderSupabase(sourceSupabase)
  if (straySql.length > 0) {
    throw new Error(
      `Refusing to stage: .sql outside supabase/tests/database/ and supabase/migrations/: ${straySql.join(', ')}`,
    )
  }

  fs.rmSync(output, { recursive: true, force: true })
  const stagedSupabase = path.join(output, 'supabase')
  const stagedMigrations = path.join(stagedSupabase, 'migrations')
  fs.mkdirSync(stagedMigrations, { recursive: true })

  fs.writeFileSync(path.join(stagedSupabase, 'config.toml'), configText)
  for (const { sourceName, stagedName, baselineFile } of plannedMigrations) {
    const sourcePath = baselineFile
      ? path.join(sourceBaseline, baselineFile)
      : path.join(sourceMigrations, sourceName)
    copyFileVerified(sourcePath, path.join(stagedMigrations, stagedName))
  }
  for (const name of HELPERS_SOURCE_NAMES) {
    copyFileVerified(path.join(sourceBaseline, name), path.join(stagedSupabase, STAGED_BASELINE_DIRECTORY, name))
  }
  fs.cpSync(path.join(sourceTests, 'database'), path.join(stagedSupabase, 'tests', 'database'), {
    recursive: true,
  })

  fs.rmSync(path.join(stagedSupabase, '.temp'), { recursive: true, force: true })
  fs.rmSync(path.join(output, '.temp'), { recursive: true, force: true })
  fs.writeFileSync(path.join(output, 'STAGED_LOCAL_TEST_ONLY.txt'), MARKER_TEXT)

  return {
    outputDirectory: output,
    migrations: plannedMigrations.map(({ sourceName, stagedName }) => ({ sourceName, stagedName })),
  }
}

function defaultRepoRoot() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
}

const invokedDirectly =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invokedDirectly) {
  try {
    const result = stageLocalWorkdir()
    console.log(`Staged ${result.outputDirectory}`)
    for (const { sourceName, stagedName } of result.migrations) {
      console.log(`  ${stagedName}  <-  ${sourceName}`)
    }
  } catch (error) {
    console.error(`stage-local-workdir: ${error.message}`)
    process.exit(1)
  }
}
